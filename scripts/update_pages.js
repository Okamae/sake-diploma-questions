function getPage(category, title, subject) {
  const ch = (category || '').match(/第[1-8]章/);
  if (!ch) return null;
  const chKey = ch[0];
  const text = (title || '') + ' ' + (subject || '');
  let bestMatch = null;
  for (const r of RULES) {
    if (r.ch !== chKey) continue;
    if (r.match.test(text)) return r.page;
  }
  // フォールバック：章の冒頭ページ
  const fallback = {
    '第1章': 9, '第2章': 55, '第3章': 109, '第4章': 155,
    '第5章': 169, '第6章': 183, '第7章': 213, '第8章': 241,
  };
  return fallback[chKey] || null;
}

function main() {
  const facts = JSON.parse(fs.readFileSync(CORE, 'utf-8'));
  let updated = 0;
  for (const f of facts) {
    const newPage = getPage(f.category, f.title, f.subject);
    if (newPage && newPage !== f.page) {
      f.page = newPage;
      updated++;
    }
  }
  fs.writeFileSync(CORE, JSON.stringify(facts, null, 2));
  console.log('Updated pages: ' + updated + ' / ' + facts.length);

  // ページ別ヒストグラム
  const hist = {};
  for (const f of facts) hist[f.page] = (hist[f.page] || 0) + 1;
  console.log('\nPage distribution (top 30):');
  const entries = Object.entries(hist).sort((a, b) => b[1] - a[1]).slice(0, 30);
  for (const [p, c] of entries) console.log('  p' + p + ': ' + c);
}

